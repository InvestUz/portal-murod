"""Generate browser types from public OpenAPI; --check fails on contract drift."""
import json
from pathlib import Path
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from drf_spectacular.generators import SchemaGenerator


def ts(schema):
    if '$ref' in schema:
        result = schema['$ref'].rsplit('/', 1)[-1]
    elif 'enum' in schema:
        result = ' | '.join(json.dumps(value) for value in schema['enum']) or 'never'
    elif any(key in schema for key in ['oneOf', 'anyOf', 'allOf']):
        key = next(key for key in ['oneOf', 'anyOf', 'allOf'] if key in schema)
        result = '('+(' & ' if key == 'allOf' else ' | ').join(ts(item) for item in schema[key])+')'
    elif schema.get('type') == 'array':
        result = '('+ts(schema.get('items', {}))+')[]'
    elif schema.get('type') in {'integer', 'number'}:
        result = 'number'
    elif schema.get('type') == 'boolean':
        result = 'boolean'
    elif schema.get('type') == 'string':
        result = 'string'
    elif schema.get('type') == 'object' or 'properties' in schema:
        props = schema.get('properties', {})
        required = schema.get('required', [])
        fields = [json.dumps(name)+('' if name in required else '?')+': '+ts(value) for name, value in props.items()]
        additional = schema.get('additionalProperties', False if props else True)
        if additional is not False:
            fields.append('[key: string]: '+(ts(additional) if isinstance(additional, dict) else 'JsonValue'))
        result = '{ '+'; '.join(fields)+' }' if fields else 'Record<string, never>'
    else:
        result = 'JsonValue'
    if schema.get('nullable') and 'null' not in result.split(' | '):
        result = '('+result+' | null)'
    return result


class Command(BaseCommand):
    def add_arguments(self, parser):
        parser.add_argument('--check', action='store_true')
        parser.add_argument('--output', default=str(settings.BASE_DIR/'apps/web/src/api.generated.ts'))

    def handle(self, *args, **options):
        schema = SchemaGenerator().get_schema(request=None, public=True)
        lines = ['// Generated by python backend/manage.py generate_api_types. Do not edit.',
                 'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };']
        for name, value in sorted(schema.get('components', {}).get('schemas', {}).items()):
            lines.append('export type '+name+' = '+ts(value)+';')
        lines.append('export interface ApiOperations {')
        for path, methods in schema['paths'].items():
            for method, operation in methods.items():
                if method not in {'get', 'post', 'put', 'patch', 'delete', 'head', 'options'}:
                    continue
                request = operation.get('requestBody', {}).get('content', {})
                request_type = ' | '.join(dict.fromkeys(ts(v.get('schema', {})) for v in request.values())) or 'never'
                responses = []
                for status, response in operation.get('responses', {}).items():
                    types = list(dict.fromkeys(ts(v.get('schema', {})) for v in response.get('content', {}).values()))
                    responses.append(json.dumps(status)+': '+(' | '.join(types) or 'null'))
                lines.append('  '+json.dumps(operation['operationId'])+': { method: '+json.dumps(method.upper())+'; path: '+json.dumps(path)+'; request: '+request_type+'; responses: { '+'; '.join(responses)+' } };')
        lines.append('}')
        value = '\n'.join(lines)+'\n'
        target = Path(options['output'])
        if options['check']:
            if not target.exists() or target.read_text() != value:
                raise CommandError('Browser API types are stale: run generate_api_types')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(value)
        self.stdout.write('Public API response types verified' if options['check'] else 'Generated public API types')
